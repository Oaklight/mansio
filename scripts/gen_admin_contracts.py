#!/usr/bin/env python3
"""Generate ``assets/contracts.js`` from ``mansio_core.contracts.admin``.

The admin UI validates every response through the generated ``parse*``
functions instead of indexing raw JSON.  Fields whose dataclass default is
``None`` (or that are omitted by ``WireResult._omit_none``) are optional;
everything else is required.  Output is deterministic: classes are sorted,
nothing time-dependent is written.

Usage:
    python scripts/gen_admin_contracts.py          # write the file
    python scripts/gen_admin_contracts.py --check  # fail if it is stale
"""

from __future__ import annotations

import importlib
import re
import sys
import types
from dataclasses import fields
from pathlib import Path
from typing import get_args, get_origin, get_type_hints

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "packages/mansio-web/src/mansio_web/admin/assets/contracts.js"

_HEADER = """\
// Generated by scripts/gen_admin_contracts.py — do not edit.
// Source: mansio_core.contracts.admin
// Envelope parsers shallow-freeze the document; models.js deep-freezes the
// nested rows and arrays.
"""

_HELPERS = """\
export class ContractMismatch extends Error {
    constructor(message) {
        super(message);
        this.name = 'ContractMismatch';
    }
}

function expectObject(raw, document) {
    if (raw === null || typeof raw !== 'object' || Array.isArray(raw)) {
        throw new ContractMismatch(`${document}: response must be a JSON object`);
    }
    return raw;
}

function requireField(raw, name, document) {
    if (!Object.prototype.hasOwnProperty.call(raw, name)) {
        throw new ContractMismatch(`${document}: missing ${name}`);
    }
}

function expectType(value, kind, message) {
    let ok;
    switch (kind) {
        case 'array': ok = Array.isArray(value); break;
        case 'object': ok = value !== null && typeof value === 'object' && !Array.isArray(value); break;
        case 'string': ok = typeof value === 'string'; break;
        case 'number': ok = typeof value === 'number' && Number.isFinite(value); break;
        case 'boolean': ok = typeof value === 'boolean'; break;
        default: ok = true;
    }
    if (!ok) throw new ContractMismatch(message);
}

export function parseErrorEnvelope(raw, document) {
    const obj = expectObject(raw, document);
    requireField(obj, 'error', document);
    return {
        error: String(obj.error),
        message: typeof obj.message === 'string' ? obj.message : '',
    };
}
"""

_JS_PRIMITIVES = {
    str: "string",
    bool: "boolean",
    int: "number",
    float: "number",
}


def _js_type(annotation) -> tuple[str, str]:
    """Return ``(jsdoc_type, check_kind)`` for a dataclass field type."""
    origin = get_origin(annotation)
    if origin in (types.UnionType,):
        args = [arg for arg in get_args(annotation) if arg is not type(None)]
        nullable = len(args) != len(get_args(annotation))
        inner, kind = _js_type(args[0]) if len(args) == 1 else ("unknown", "unknown")
        return (f"{inner}|null" if nullable else inner, kind)
    if annotation in _JS_PRIMITIVES:
        kind = _JS_PRIMITIVES[annotation]
        return kind, kind
    if annotation is list or get_origin(annotation) is list:
        return "Array<Object>", "array"
    if annotation is dict or get_origin(annotation) is dict:
        return "Object", "object"
    return "unknown", "unknown"


def _document_name(cls) -> str:
    doc = cls.__doc__ or ""
    match = re.search(r"Response of ``([A-Z]+ [^`]+)``", doc)
    return match.group(1).strip() if match else cls.__name__


def _optional_fields(cls) -> frozenset[str]:
    omit = getattr(cls, "_omit_none", frozenset())
    names = set(omit)
    for item in fields(cls):
        if item.default is None:
            names.add(item.name)
    return frozenset(names)


def generate() -> str:
    contracts = importlib.import_module("mansio_core.contracts.admin")
    wire_result = contracts.WireResult
    classes = [
        obj
        for name, obj in vars(contracts).items()
        if isinstance(obj, type)
        and issubclass(obj, wire_result)
        and obj is not wire_result
        and obj.__module__ == contracts.__name__
    ]
    classes.sort(key=lambda cls: cls.__name__)

    out = [_HEADER, _HELPERS]
    for cls in classes:
        name = cls.__name__
        document = _document_name(cls)
        optional = _optional_fields(cls)
        custom = cls.to_dict is not wire_result.to_dict

        out.append(f"// {document}\n")
        if custom:
            out.append(
                f"/**\n * @typedef {{Object<string, unknown>}} {name}\n"
                f" * The document is the stats object itself, not a field of it.\n */\n"
            )
            out.append(
                f"export function parse{name}(raw) {{\n"
                f"    return Object.freeze({{ ...expectObject(raw, {document!r}) }});\n"
                f"}}\n"
            )
            continue

        hints = get_type_hints(cls)
        property_lines = []
        for item in fields(cls):
            js_type, _kind = _js_type(hints.get(item.name, item.type))
            if item.name in optional:
                property_lines.append(f" * @property {{{js_type}}} [{item.name}]")
            else:
                property_lines.append(f" * @property {{{js_type}}} {item.name}")
        out.append(
            "/**\n * @typedef {Object} " + name + "\n" + "\n".join(property_lines) + "\n */\n"
        )

        body = [f"export function parse{name}(raw) {{"]
        body.append(f"    const document = {document!r};")
        body.append("    const obj = expectObject(raw, document);")
        for item in fields(cls):
            js_type, kind = _js_type(hints.get(item.name, item.type))
            if item.name in optional:
                body.append(
                    f"    if (obj.{item.name} !== undefined && obj.{item.name} !== null) {{"
                )
                body.append(
                    f"        expectType(obj.{item.name}, {kind!r}, `${{document}}: {item.name} must be {kind}`);"
                )
                body.append("    }")
            else:
                body.append(f"    requireField(obj, {item.name!r}, document);")
                body.append(
                    f"    expectType(obj.{item.name}, {kind!r}, `${{document}}: {item.name} must be {kind}`);"
                )
        body.append("    return Object.freeze({ ...obj });")
        body.append("}\n")
        out.append("\n".join(body))

    return "\n".join(out)


def main(argv: list[str]) -> int:
    generated = generate()
    if "--check" in argv:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != generated:
            print(
                f"{TARGET.relative_to(ROOT)} is stale; run "
                "`python scripts/gen_admin_contracts.py`.",
                file=sys.stderr,
            )
            return 1
        return 0
    TARGET.write_text(generated, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
